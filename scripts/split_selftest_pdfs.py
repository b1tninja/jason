"""Writes ``ui/src/views/splitSelfTestData.ts``: two tiny made-up PDFs, embedded in the console, that the browser draws once at start to
prove its decoders work (docs/pdf-splitter-client-side.md, "What did not work until configured").

Each is one 64 by 64 page holding one image whose left half is black and whose right half is white: a JPEG 2000 image (JPXDecode) and
a 1-bit CCITT Group 4 image. pdf.js draws JPEG 2000 as a white page, with no error, when its wasm decoder is not found; the self-test
sees that (the left half is not dark) and the console falls back to the server's pictures for the session.

    python scripts/split_selftest_pdfs.py            # rewrites the TypeScript data file
"""

from __future__ import annotations

import base64
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from PIL import Image  # noqa: E402

from client_pdf_make import Pdf, ccitt_bytes  # noqa: E402

SIDE = 64
OUT = Path(__file__).resolve().parents[1] / "ui" / "src" / "views" / "splitSelfTestData.ts"


def half_black(mode: str) -> Image.Image:
    img = Image.new(mode, (SIDE, SIDE), 255 if mode != "1" else 1)
    black = (0, 0, 0) if mode == "RGB" else 0
    for x in range(SIDE // 2):
        for y in range(SIDE):
            img.putpixel((x, y), black)
    return img


def one_page(dictionary: bytes, data: bytes) -> bytes:
    pdf = Pdf()
    pages = pdf.reserve()
    im = pdf.stream(dictionary, data)
    cs = pdf.stream(b"", f"q {SIDE} 0 0 {SIDE} 0 0 cm /Im0 Do Q".encode())
    pg = pdf.add(f"<< /Type /Page /Parent {pages} 0 R /MediaBox [0 0 {SIDE} {SIDE}] /Resources << /XObject << /Im0 {im} 0 R >> >> /Contents {cs} 0 R >>".encode())
    pdf.set(pages, f"<< /Type /Pages /Count 1 /Kids [{pg} 0 R] >>".encode())
    root = pdf.add(f"<< /Type /Catalog /Pages {pages} 0 R >>".encode())
    tmp = Path(__file__).with_name("_selftest.tmp")
    try:
        pdf.write(tmp, root)
        return tmp.read_bytes()
    finally:
        tmp.unlink(missing_ok=True)


def jpx() -> bytes:
    # One grey component: no colour transform to disagree about, so the test asks only whether the decoder runs and puts the black on the left.
    b = io.BytesIO()
    half_black("L").save(b, "JPEG2000", irreversible=False)
    return one_page(f"/Type /XObject /Subtype /Image /Width {SIDE} /Height {SIDE} /ColorSpace /DeviceGray /BitsPerComponent 8 /Filter /JPXDecode".encode(), b.getvalue())


def ccitt() -> bytes:
    data = ccitt_bytes(half_black("1"))
    d = (f"/Type /XObject /Subtype /Image /Width {SIDE} /Height {SIDE} /ColorSpace /DeviceGray /BitsPerComponent 1 "
         f"/Filter /CCITTFaxDecode /DecodeParms << /K -1 /Columns {SIDE} /Rows {SIDE} /BlackIs1 true >>").encode()
    return one_page(d, data)


def main() -> None:
    parts = {"JPEG 2000": jpx(), "CCITT Group 4": ccitt()}
    lines = ["// Generated by scripts/split_selftest_pdfs.py; do not edit by hand.",
             "// Two tiny made-up PDFs (64 by 64, left half black, right half white) the browser draws once to prove its decoders work.",
             "export interface SelfTestPage { codec: string; base64: string }", "export const SELF_TEST_PAGES: SelfTestPage[] = ["]
    for codec, data in parts.items():
        lines.append(f'  {{ codec: "{codec}", base64: "{base64.b64encode(data).decode()}" }},')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({', '.join(f'{k} {len(v)} bytes' for k, v in parts.items())})")


if __name__ == "__main__":
    main()
