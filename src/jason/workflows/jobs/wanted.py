"""What the six families still want, diffed against what exists, so the list in docs/workflows-engine.md stays true.

Every family module (``jason.workflows.defs.<family>``) has a ``WANTED`` tuple of strings naming the checks, jobs, and approvals
plan kinds (and cases of a kind) its person steps wait for. The families write the strings in their own styles (``job:NAME``,
``job NAME: why``, ``plan:KIND -- why``, ``kind``/``case`` for a kind and a case of ``gmail-drafts``); ``parse`` reads all of
them. This module diffs the names against what is registered *now*:

- a **job** when it is in ``readers.JOBS``; a wanted job that has a descriptor in ``jason.workflows.jobs`` but whose family is
  not in ``READY`` is "descriptor written, not yet registered"; one in ``UNDESCRIBED`` has no single existing command to point
  at; the rest are listed bare;
- a **plan kind** when it is a key or alias in the approvals registry, and a **case** when it is ``gmail-drafts/<case>`` and
  the case is in ``gmail_drafts.CASES``. This module registers no approvals kind: that is the board's call, so the unmet are
  only listed.

``markdown()`` renders the subsection of the engine doc and ``python -m jason.workflows.jobs.wanted --write`` rewrites it in
place (between the two markers); ``tests/test_workflows_wanted.py`` fails when the doc and the diff differ. It reads source
tables and writes only the doc, when asked.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from importlib import import_module
from pathlib import Path
from typing import Iterable

FAMILIES: tuple[str, ...] = ("members", "board", "money", "records", "property", "platform")
BEGIN = "<!-- wanted:begin (generated by python -m jason.workflows.jobs.wanted --write; do not edit by hand) -->"
END = "<!-- wanted:end -->"
DOC = Path(__file__).resolve().parents[4] / "docs" / "workflows-engine.md"

_LINE = re.compile(r"^(check|job|plan|kind|case)(?::|\s+)\s*([\w./+\-]+)")
_KIND = {"check": "check", "job": "job", "plan": "plan", "kind": "plan", "case": "plan"}


@dataclass(frozen=True)
class Want:
    family: str
    kind: str          # "check", "job", or "plan"
    name: str


def parse(line: str) -> tuple[str, str] | None:
    """``(kind, name)`` for a WANTED line that names a check, a job, or a plan kind or case; ``None`` for the other lines
    (templates, commands, roles, and the engine items some families list)."""
    found = _LINE.match(line.strip())
    return (_KIND[found.group(1)], found.group(2)) if found else None


def wants(families: Iterable[str] = FAMILIES) -> list[Want]:
    """Every distinct wanted check, job, and plan kind of each family, in the family's order."""
    out: list[Want] = []
    for family in families:
        try:
            lines = getattr(import_module(f"jason.workflows.defs.{family}"), "WANTED", ())
        except ModuleNotFoundError as exc:
            if exc.name == f"jason.workflows.defs.{family}":
                continue
            raise
        seen: set[tuple[str, str]] = set()
        for line in lines:
            got = parse(line)
            if got and got not in seen:
                seen.add(got)
                out.append(Want(family, *got))
    return out


def registered_plans() -> tuple[set[str], set[str]]:
    """(plan kind keys and aliases, ``gmail-drafts/<case>`` names) in the approvals registry now."""
    from jason.approvals import registry
    from jason.approvals.kinds import gmail_drafts

    kinds = {k for kind in registry.kinds() for k in (kind.key, *kind.aliases)}
    return kinds, {f"gmail-drafts/{c.key}" for c in gmail_drafts.CASES}


def report(families: Iterable[str] = FAMILIES) -> dict[str, object]:
    """The diff: for each family its wanted jobs (split four ways) and its unmet plan kinds and cases, with the counts. The
    checks are not here: a family registers its own reads, and they change often."""
    from jason.workflows import jobs, readers

    kinds, cases = registered_plans()
    described = {d.name: d for d in jobs.DESCRIPTORS}
    rows: dict[str, dict[str, object]] = {}
    for family in families:
        mine = wants([family])
        row: dict[str, object] = {"waiting": [], "bare": [], "undescribed": [], "plans": [], "jobs": 0, "jobs_met": 0,
                                  "plans_total": 0, "plans_met": 0}
        for w in mine:
            if w.kind == "job":
                row["jobs"] = int(row["jobs"]) + 1
                if w.name in readers.JOBS:
                    row["jobs_met"] = int(row["jobs_met"]) + 1
                elif w.name in described:
                    row["waiting"].append(w.name)
                elif w.name in jobs.UNDESCRIBED:
                    row["undescribed"].append(w.name)
                else:
                    row["bare"].append(w.name)
            elif w.kind == "plan":
                row["plans_total"] = int(row["plans_total"]) + 1
                if w.name in kinds or w.name in cases:
                    row["plans_met"] = int(row["plans_met"]) + 1
                else:
                    row["plans"].append(w.name)
        rows[family] = row
    return rows


def markdown(families: Iterable[str] = FAMILIES) -> str:
    """The generated subsection body (between the markers): counts for each family, the descriptors waiting for their family,
    the jobs with no single command to point at, and the plan kinds and cases wanted (none registered here)."""
    from jason.workflows import jobs

    families = tuple(families)
    rows = report(families)
    described = {d.name: d for d in jobs.DESCRIPTORS}
    out = [
        "Generated from each family's `WANTED` against what is registered (`jason.workflows.jobs.wanted`; "
        "`tests/test_workflows_wanted.py` fails when this list drifts). A job is a **descriptor** of an existing jason command: a "
        "person runs the command, and the engine only recognizes the queued job by its words and reads how it ended. "
        "`jobs.READY` names the families whose descriptors are registered in `readers.JOBS`; a family joins it in the change "
        "that makes its steps job steps and updates its own tests (each family's test pins its wanted names as not yet registered). "
        "No approvals kind is added here: that is the board's call, so the kinds are only listed.",
        "",
        "| Family | Jobs wanted | Registered | Descriptor written, family not ready | No single command | Neither descriptor nor reason | Plan kinds and cases wanted (unmet) |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in families:
        r = rows[f]
        out.append(f"| {f} | {r['jobs']} | {r['jobs_met']} | {len(r['waiting'])} | {len(r['undescribed'])} | "
                   f"{len(r['bare'])} | {len(r['plans'])} |")
    out += ["", "**Registered job families (`jobs.READY`):** " + (", ".join(f"`{x}`" for x in sorted(jobs.READY)) or "none")
            + ". A registered job leaves its family's `WANTED`, so a ready family's wanted jobs are only those it has not described.", ""]

    waiting = [(f, n) for f in families for n in rows[f]["waiting"]]
    if waiting:
        out += ["**Descriptor written, not yet registered** (the command a person runs; promoted by adding the family to `jobs.READY`):", ""]
        for f in families:
            names = rows[f]["waiting"]
            if names:
                out.append(f"- {f}: " + "; ".join(f"`{n}` = `{described[n].command}`" for n in names))
        out.append("")
    undescribed = [(f, n) for f in families for n in rows[f]["undescribed"]]
    if undescribed:
        out += ["**No single existing command to point at:**", ""]
        for f in families:
            for n in rows[f]["undescribed"]:
                out.append(f"- {f}: `{n}` -- {jobs.UNDESCRIBED[n]}")
        out.append("")
    bare = [(f, n) for f in families for n in rows[f]["bare"]]
    if bare:
        out += ["**Wanted job names with neither a descriptor nor a reason (to look at):** "
                + ", ".join(f"{f} `{n}`" for f, n in bare) + ".", ""]
    plans = [(f, n) for f in families for n in rows[f]["plans"]]
    out += ["**Plan kinds and cases still wanted (the board's call; none is registered by this work):**", ""]
    for f in families:
        names = rows[f]["plans"]
        if names:
            out.append(f"- {f}: " + ", ".join(f"`{n}`" for n in names))
    if not plans:
        out.append("- none")
    return "\n".join(out).rstrip() + "\n"


def current(doc: Path = DOC) -> str:
    """The text between the markers in the doc, or ``""`` when the markers are not there."""
    text = doc.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return ""
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def write(doc: Path = DOC) -> bool:
    """Rewrite the generated block in the doc. False when nothing changed; a doc without the markers is an error."""
    text = doc.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{doc} has no generated block: add the two markers first")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    new = head + BEGIN + "\n\n" + markdown() + "\n" + END + tail
    if new == text:
        return False
    doc.write_text(new, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "--write" in args:
        print("rewritten" if write() else "unchanged")
        return 0
    if "--check" in args:
        same = current().strip() == markdown().strip()
        print("the doc matches" if same else "the doc differs: run python -m jason.workflows.jobs.wanted --write")
        return 0 if same else 1
    sys.stdout.write(markdown())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
