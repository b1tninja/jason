@dataclass(frozen=True)
class SystemRecords:
    """One system: the obligations that apply with their periods, the reports of it no obligation could be named for,
    the obligations that do not apply with the fact that decided each, and the undetermined ones as questions."""

    system: LifeSafetySystem
    obligations: tuple[ObligationRecords, ...] = ()
    unassigned: tuple[tuple[Placed, str], ...] = ()
    does_not_apply: tuple[Finding, ...] = ()
    undetermined: tuple[Finding, ...] = ()
    not_read: tuple[Filing, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        return {"system": self.system.as_dict(), "obligations": [o.as_dict() for o in self.obligations],
                "unassigned": [{**p.as_dict(), "reason": why} for p, why in self.unassigned],
                "doesNotApply": [f.as_dict() for f in self.does_not_apply],
                "undetermined": [f.as_dict() for f in self.undetermined],
                "notRead": [f.as_dict() for f in self.not_read]}


@dataclass(frozen=True)
class Records:
    as_of: date
    systems: tuple[SystemRecords, ...] = ()
    unplaced: tuple[Unplaced, ...] = ()
    recitals: tuple[Recital, ...] = ()
    questions: tuple[str, ...] = ()
    other_filings: int = 0               # reports in the filing log from vendors no listed system names
    listed: bool = True                  # False where the specification lists no systems
    community: str = ""
    sources: tuple[str, ...] = field(default_factory=tuple)

    def of(self, key: str) -> "Records | None":
        """The same result for one system; None when no system has the key."""
        one = tuple(s for s in self.systems if s.system.key == key)
        if not one:
            return None
        return replace(self, systems=one)

    def summary(self) -> list[dict[str, Any]]:
        """Per system and obligation, how many periods stand covered, partly on file, not on file, and not yet due;
        ``note`` says why where no period could be listed."""
        return [{"system": s.system.key, "obligation": row_name(o.row), "cadence": cadence_of(o.row),
                 "periods": len(o.periods), **o.counts(), "note": "" if o.periods else o.counted_how}
                for s in self.systems for o in s.obligations]

    def as_dict(self) -> dict[str, Any]:
        return {"community": self.community, "asOf": self.as_of.isoformat(), "systems": [s.as_dict() for s in self.systems],
                "summary": self.summary(), "unplaced": [u.as_dict() for u in self.unplaced],
                "recordKeeping": [r.as_dict() for r in self.recitals], "questions": list(self.questions),
                "otherFilings": self.other_filings, "sources": list(self.sources), "caveats": list(CAVEATS)}


def _corrected(placed: Sequence[Placed]) -> list[Placed]:
    """Each placed report with, where it reports deficiencies, the earliest later report of the same system and
    buildings that reads passed with none open."""
    out = []
    for p in placed:
        later = None
        if p.report.reports_deficiencies:
            found = [q.report for q in placed if q.system is p.system and q.report.day and p.report.day
                     and q.report.day > p.report.day and set(p.slots) <= set(q.slots)
                     and q.report.result == "passed" and not q.report.reports_deficiencies]
            later = min(found, key=lambda r: r.day) if found else None
        out.append(Placed(p.report, p.system, p.slots, later))
    return out


def completeness(community: Any, readings: Iterable[Mapping[str, Any]], *, as_of: date,
                 completions: Iterable[Completion] = (), filings: Iterable[Filing] = (),
                 calendar: Iterable[Mapping[str, Any]] = (), recitals: Iterable[Recital] = (),
                 applicability: SystemApplicability | None = None) -> Records:
    """For each of the community's systems and each obligation that applies to it, the periods and what is on file
    in each; with what could not be placed and why, what does not apply and the fact that decided it, and what is
    undetermined as a question.

    ``readings`` are rows of the readings store (other kinds are passed over). ``completions`` are a person's records
    with the obligations each one's assignment covers. ``filings`` are the filing log's reports no reading covers.
    ``calendar`` are the obligations' rows of ``jason deadlines``. ``recitals`` are the record-keeping provisions as
    ``recite`` found them. Pure: it reads nothing.
    """
    result = applicability or applicable(community, as_of=as_of)
    systems = result.systems
    calendar_by = {str(r.get("name")): r for r in calendar}
    unplaced: list[Unplaced] = []

    placed: list[Placed] = []
    for row in readings:
        if row.get("kind") not in (None, REPORT_KIND):
            continue
        report = Report.of(row)
        system, slots, why = place(report, systems)
        if system is None:
            unplaced.append(Unplaced(report.label, why, report.id))
        else:
            placed.append(Placed(report, system, slots))
    placed = _corrected(placed)

    # A completion is a record of one obligation for one system, or it is unplaced.
    applying: dict[str, list[Finding]] = {}
    for f in result.applies:
        if f.system is not None:
            applying.setdefault(row_name(f.row), []).append(f)
    done: dict[tuple[str, str], list[Completion]] = {}
    for c in completions:
        named = [n for n in c.obligations if n in applying]
        if not named:
            continue                                     # not a record of any system's obligation
        if len(c.obligations) != 1:
            unplaced.append(Unplaced(c.label, f"its assignment covers {len(c.obligations)} obligations, and the record "
                                              "does not say which", c.key))
        elif len(applying[named[0]]) != 1:
            unplaced.append(Unplaced(c.label, f"the obligation applies to {len(applying[named[0]])} systems, and the "
                                              "record does not say which", c.key))
        elif c.done is None:
            unplaced.append(Unplaced(c.label, "the record gives no date it was done", c.key))
        else:
            done.setdefault((applying[named[0]][0].system.key, named[0]), []).append(c)

    by_vendor: dict[str, list[Filing]] = {}
    other = 0
    for filing in filings:
        keys = tuple(s.key for s in systems if filing.vendor and filing.vendor.lower() in
                     (s.servicer.lower(), s.monitor.lower()))
        if not keys:
            other += 1
        for key in keys:
            by_vendor.setdefault(key, []).append(Filing(filing.vendor, filing.name, filing.sent, filing.where,
                                                        filing.file_id, keys))

    out: list[SystemRecords] = []
    for system in systems:
        part = result.of(system)
        rows = [f.row for f in part.applies]
        mine = [p for p in placed if p.system is system]
        assigned: dict[int, list[Placed]] = {}
        unassigned: list[tuple[Placed, str]] = []
        for p in mine:
            row, why = obligation_for(p.report, rows)
            if row is None:
                unassigned.append((p, why))
            else:
                assigned.setdefault(id(row), []).append(p)
        obligations = tuple(
            _records(f.row, f, sorted(assigned.get(id(f.row), []), key=lambda p: (p.report.day, p.slots)),
                     done.get((system.key, row_name(f.row)), []), as_of, calendar_by.get(row_name(f.row)))
            for f in part.applies)
        out.append(SystemRecords(system, obligations, tuple(unassigned), part.does_not_apply, part.undetermined,
                                 tuple(by_vendor.get(system.key, ()))))

    base = Facts.build(profile=profile_facts(community), as_of=as_of)
    reached: list[Recital] = []
    for recital in recitals:
        reaches, asks = [], []
        for system in systems:
            parts = partition([recital.rule], base.merge(system_facts(system)))
            if parts.applies:
                reaches.append(system.name)
            for _, verdict in parts.undetermined:
                asks.append(Finding(recital.rule, system, verdict).question())
        reached.append(Recital(recital.rule, recital.found, recital.words, recital.source, recital.reason,
                               tuple(reaches), tuple(asks)))

    # A system's open answers, and (where the specification lists no systems) the question of which it has.
    asked = [f for f in result.undetermined if f.system is not None or SUBJECT_FACTS.intersection(f.verdict.missing)]
    questions = tuple(dict.fromkeys(f.question() for f in asked))
    return Records(as_of, tuple(out), tuple(unplaced), tuple(reached), questions, other, bool(systems),
                   str(getattr(community, "name", "") or ""))


