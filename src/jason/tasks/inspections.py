def _completions(data_dir: Path, community: Any) -> list[Completion]:
    from jason.community.schedule import assignments
    from jason.tasks.schedule import completions

    rows = completions(data_dir)
    if not rows:
        return []
    covers = {a.key: tuple(c.split(":", 1)[1] for c in a.covers if c.startswith("obligation:"))
              for a in assignments(community)}
    return [Completion(str(r.get("key") or ""), _day(r.get("done")), str(r.get("by") or ""), str(r.get("evidence") or ""),
                       _day(r.get("due")), covers.get(str(r.get("key") or ""), ())) for r in rows]


def _library(data_dir: Path) -> tuple[dict[str, Any], ...]:
    from jason.tasks.library import load

    try:
        return load(data_dir)
    except Exception:  # noqa: BLE001 - an unreadable library is no library; the page says which stores it read
        return ()


def _filings(data_dir: Path, read_ids: set[str], read_shas: set[str]) -> list[Filing]:
    """The filing log's inspection reports that no reading covers: not the Drive file's own reading, and not a
    library copy with the same bytes."""
    from jason.tasks.vendor_files import LOG

    path = Path(data_dir) / "drive" / LOG
    if not path.is_file():
        return []
    out, seen = [], set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        file_id = str(row.get("file_id") or "")
        if row.get("kind") != REPORT_KIND or f"drive-{file_id}" in read_ids or row.get("sha256") in read_shas:
            continue
        if (file_id or row.get("sha256")) in seen:
            continue
        seen.add(file_id or row.get("sha256"))
        out.append(Filing(str(row.get("vendor") or ""), str(row.get("name") or ""), str(row.get("at") or "")[:10],
                          str(row.get("where") or ""), file_id))
    return out


def review(data_dir: Path | str, community: Any, *, as_of: date | None = None) -> Records:
    """The completeness of the life safety records from the stores on disk: the readings, the library's inspection
    reports no reading covers, a person's completions, the filing log, the obligations' calendar rows, and the
    record-keeping provisions from the shelf. It reads disk only and writes nothing."""
    from jason.tasks.deadlines import obligation_rows
    from jason.tasks.document_models import load

    data_dir = Path(data_dir)
    day = as_of or date.today()
    readings = [r for r in load(data_dir) if r.get("kind") == REPORT_KIND]
    read_ids = {str(r.get("id")) for r in readings if r.get("model")}
    have = {str(r.get("id")) for r in readings}
    library = _library(data_dir)
    read_shas = {str(r.get("sha256")) for r in library if str(r.get("id")) in read_ids and r.get("sha256")}
    for row in library:                                   # a library report the models never saw
        if row.get("kind") == REPORT_KIND and str(row.get("id")) not in have:
            readings.append({"id": row.get("id"), "name": row.get("name"), "kind": REPORT_KIND, "model": None,
                             "confidential": row.get("confidential"), "hasText": True})
    found = completeness(
        community, readings, as_of=day, completions=_completions(data_dir, community),
        filings=_filings(data_dir, read_ids, read_shas), calendar=obligation_rows(data_dir, community, today=day),
        recitals=[recite(data_dir, rule) for rule in RECORD_RULES])
    sources = ("documents/readings.json (jason models)", "library.db (jason library)", "schedule/done.jsonl",
               "drive/vendor-files.jsonl", "authorities/publications")
    return replace(found, sources=sources)


