@dataclass(frozen=True)
class Period:
    """One period of an obligation for a system. ``start`` is its first day, None for the day the count opens on.
    ``missing`` are the buildings with nothing on file in it (empty for a system not divided by building)."""

    start: date | None
    end: date
    status: Coverage
    reports: tuple[Placed, ...] = ()
    completions: tuple[Completion, ...] = ()
    missing: tuple[str, ...] = ()
    note: str = ""

    @property
    def label(self) -> str:
        return f"on {self.end}" if self.start is None else f"{self.start} to {self.end}"

    def as_dict(self) -> dict[str, Any]:
        return {"start": self.start.isoformat() if self.start else None, "end": self.end.isoformat(),
                "status": self.status.value, "reports": [p.as_dict() for p in self.reports],
                "completions": [c.as_dict() for c in self.completions], "missing": list(self.missing), "note": self.note}


@dataclass(frozen=True)
class ObligationRecords:
    """One obligation that applies to a system, and its periods. ``counted_from`` is None, and ``periods`` empty,
    where the row gives no first due date and no record is on file to count from. ``earlier`` are records dated
    before the first period. ``calendar`` is the obligation's own row of ``jason deadlines``."""

    row: Any
    finding: Finding
    counted_from: date | None = None
    counted_how: str = ""
    periods: tuple[Period, ...] = ()
    earlier: tuple[Placed, ...] = ()
    calendar: Mapping[str, Any] | None = None

    def counts(self) -> dict[str, int]:
        out = {c.value: 0 for c in Coverage}
        for p in self.periods:
            out[p.status.value] += 1
        return out

    def as_dict(self) -> dict[str, Any]:
        cal = self.calendar or {}
        return {"obligation": row_name(self.row), "authority": getattr(self.row, "authority", ""),
                "cadence": cadence_of(self.row), "countedFrom": self.counted_from.isoformat() if self.counted_from else None,
                "countedHow": self.counted_how, "periods": [p.as_dict() for p in self.periods], "counts": self.counts(),
                "earlier": [p.as_dict() for p in self.earlier],
                "calendar": {k: cal.get(k) for k in ("next", "standing", "lastDone", "daysLeft")} if cal else None}


def cadence_of(row: Any) -> str:
    if getattr(row, "fixed", False):
        return f"yearly by {row.deadline(2000):%B} {row.day}"
    return row.cadence() if months_of(row) else "no frequency"


def _spans(row: Any, days: Sequence[date], as_of: date, counted: date | None = None
           ) -> tuple[date | None, str, list[tuple[date | None, date]]]:
    """The periods of a row as (the day before the first day, or None for the opening day; the last day), with the day
    counting starts on and how it was chosen. ``days`` are the records on file and ``counted`` the earliest day the
    calendar's own evidence gives (a payment). No periods where there is nothing to count from."""
    months = months_of(row)
    first_due = getattr(row, "first_due", None)
    done_on = getattr(row, "done_on", None)
    known = sorted({*days, *([done_on] if done_on else []), *([counted] if counted else [])})
    if not months:
        return None, "The row gives no frequency, so it has no periods.", []
    opening = False
    if getattr(row, "fixed", False):
        base = first_due or (known[0] if known else None)
        if base is None:
            return None, "No record is on file to count from, so no period can be listed.", []
        anchor = row.deadline(base.year) if row.deadline(base.year) >= base else row.deadline(base.year + 1)
        how = "the row's yearly deadline"
    elif first_due is not None:
        anchor, how = first_due, "the row's first due date"
    elif known:
        anchor, opening = known[0], True
        how = ("the earliest record on file" if anchor in days
               else "the date the row gives for its last record" if done_on == anchor
               else "the earliest payment jason deadlines counts for it (a payment opens the count; it is not a record)")
    else:
        return None, ("The row gives no first due date and no record is on file to count from, so no period can be "
                      "listed."), []
    spans: list[tuple[date | None, date]] = []
    k = 0
    while True:
        end = add_months(anchor, k * months)
        spans.append((None if opening and k == 0 else add_months(anchor, (k - 1) * months), end))
        if end > as_of:
            break
        k += 1
    return anchor, how, spans


def _records(row: Any, finding: Finding, placed: Sequence[Placed], done: Sequence[Completion], as_of: date,
             calendar: Mapping[str, Any] | None) -> ObligationRecords:
    system = finding.system
    slots = slots_of(system) if system else ("",)
    days = [p.report.day for p in placed if p.report.day] + [c.done for c in done if c.done]
    counted = _day((calendar or {}).get("firstDone"))
    anchor, how, spans = _spans(row, days, as_of, counted)
    done_on = getattr(row, "done_on", None)
    periods: list[Period] = []
    for k, (before, end) in enumerate(spans):
        inside = (lambda d: d == end) if before is None else (lambda d: before < d <= end)  # noqa: E731
        reports = tuple(p for p in placed if p.report.day and inside(p.report.day))
        completions = tuple(c for c in done if c.done and inside(c.done))
        opening = before is None
        covered = {s for p in reports for s in p.slots}
        missing = () if completions or opening else tuple(s for s in slots if s not in covered)
        if reports or completions:
            status = Coverage.COVERED if not missing else Coverage.NOT_YET_DUE if end > as_of else Coverage.PARTLY
        else:
            status = Coverage.NOT_YET_DUE if end > as_of else Coverage.NOT_ON_FILE
            missing = ()
        note = ""
        if done_on and inside(done_on) and not any(p.report.day == done_on for p in reports):
            note = f"The row dates a record on {done_on}; no reading of it is on file."
        elif opening and not reports and not completions:
            note = "jason deadlines counts a payment on this day; no report for it is on file."
        periods.append(Period(None if opening else before + timedelta(days=1), end, status, reports, completions,
                              tuple(s for s in missing if s), note))
    first_day = periods[0].start or periods[0].end if periods else None
    earlier = tuple(p for p in placed if first_day and p.report.day and p.report.day < first_day)
    return ObligationRecords(row, finding, anchor, how, tuple(periods), earlier, calendar)


