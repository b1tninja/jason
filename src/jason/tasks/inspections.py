# Placing a record: which system, which buildings, which obligation.


def slots_of(system: LifeSafetySystem) -> tuple[str, ...]:
    """The buildings a system serves, as words; one empty word where the specification does not divide it."""
    return tuple(str(getattr(s, "value", s)) for s in system.serves) or ("",)


def place(report: Report, systems: Sequence[LifeSafetySystem]) -> tuple[LifeSafetySystem | None, tuple[str, ...], str]:
    """The system and buildings a report belongs to by its reading's own fields, or the reason it has none."""
    if not report.model:
        return None, (), ("not read: no text on disk" if not report.has_text
                          else "not read: no reader has read it (jason models)")
    if report.kind is None:
        said = f" (it says \"{report.system_word}\")" if report.system_word else ""
        return None, (), f"{report.reader} does not say which system{said}: the field system"
    if report.day is None:
        return None, (), f"{report.reader} gives no inspection date: the field inspection_date"
    same = [s for s in systems if s.kind is report.kind]
    if not same:
        return None, (), f"the reading names {_a(report.kind.label)}; the specification lists no such system"
    whole = [s for s in same if not s.serves]
    if report.buildings:
        holders = [s for s in same if set(report.buildings) <= set(slots_of(s))]
        if len(holders) == 1:
            return holders[0], report.buildings, ""
        if len(holders) > 1:
            return None, (), f"more than one listed {report.kind.label} serves building {', '.join(report.buildings)}"
        if len(same) == 1 and whole:
            return same[0], ("",), ""                # the only such system, which the specification does not divide
        return None, (), (f"the reading says building {', '.join(report.buildings)}, which no one listed "
                          f"{report.kind.label} serves")
    if len(same) == 1 and whole:
        return same[0], ("",), ""
    return None, (), f"{report.reader} does not say which building: the field building"


def _a(label: str) -> str:
    return ("an " if label[:1].lower() in "aeiou" else "a ") + label


def months_of(row: Any) -> int:
    """A row's interval in months: its own, or twelve for a fixed yearly deadline; 0 for a row with no frequency."""
    return int(getattr(row, "months", 0) or 0) or (12 if getattr(row, "fixed", False) else 0)


def obligation_for(report: Report, rows: Sequence[Any]) -> tuple[Any | None, str]:
    """Which of a system's applicable obligations a report is the record of, or why none can be named."""
    timed = [r for r in rows if months_of(r)]
    if not timed:
        return None, "no obligation with a frequency applies to the system"
    if report.interval_months:
        match = [r for r in timed if months_of(r) == report.interval_months]
        if len(match) == 1:
            return match[0], ""
        if not match:
            return None, f"the reading says every {report.interval_months} months, and no obligation of the system runs so"
        return None, (f"{len(match)} obligations of the system run every {report.interval_months} months, and the "
                      "reading does not say which")
    if len(timed) == 1:
        return timed[0], ""
    return None, (f"{len(timed)} obligations apply to the system, and {report.reader} does not say which inspection "
                  "it records: the field interval_months")


