"""Which inspection periods have a record on file: the completeness lens over the life safety records.

``jason inspections`` asks, for each of the profile's life safety systems and each obligation that applies to it
(``jason.community.life_safety.applicable``), which periods have a report on file and which do not. It is the
"Completeness" lens of docs/ingestion-and-review.md for one collection: which documents should the collection hold
that it does not?

**What counts as on file.** Two kinds of record, and nothing else:

- an inspection-report reading (``data/documents/readings.json``, kind ``inspection_report``), placed by the reading's
  own fields: ``system``, ``building`` (or ``buildings``), and ``inspection_date``;
- a completion a person recorded (``data/schedule/done.jsonl``, ``jason schedule --done``), where its assignment
  covers one obligation and that obligation applies to one system.

A payment is not a record here (``jason deadlines`` shows payments), and a file's name places nothing. A reading that
lacks a field is listed as **unplaced** with the field it lacks, never guessed into a period. A report jason has on
disk but no reader has read (a library file with no reading, a vendor's report in the filing log,
``data/drive/vendor-files.jsonl``) is listed as **not read**.

**Periods.** One scheduler: the frequency is the obligation row's (``Obligation.months``), the date arithmetic is
``jason.tasks.deadlines.add_months``, and each obligation's own calendar row (``deadlines.obligation_rows``: next due,
standing) is shown beside its periods. A row with a first due date is counted in periods that end on it and on each
date after it by the frequency. A row without one is counted from the earliest day the calendar would count from: the
earliest record on file, the date the row gives for its last record, or the earliest payment the calendar counts
(``firstDone``). That day opens the count, and each period after it ends one interval later, the way the calendar
counts the next due date from the last record. A payment only opens the count; it never covers a period. The period
still running closes the list as "not yet due". A row with nothing to count from has no period to list, and says so.
A report made late falls in the next period.

**Which obligation a report shows.** Where one obligation with a frequency applies to the system, a report of that
system is its record. Where several apply, the reading must say which: ``interval_months`` (3 for a quarterly
inspection, 12 for an annual one). A reading that does not is listed under the system as not assigned.

**Deficiencies.** A report that reports deficiencies is shown with its count. A later reading of the same system and
building whose result is passed with none open is named beside it, as that report's result and not as a record of the
repair; otherwise "no correction on file".

**The record-keeping rule** is recited from the authorities shelf (``recite``): the words of each ``RecordRule`` row
(``jason.community.fire_protection.RECORD_RULES``) as the shelf's copy of the publication prints them, with the
citation. A provision the shelf does not print is cited and said to be missing; it is never quoted from memory.

``completeness`` is pure. ``review`` reads the stores and calls it; ``write`` saves the page. Nothing here calls an
outside service.
"""

