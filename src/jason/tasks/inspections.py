def _day(value: Any) -> date | None:
    text = str(value or "")
    try:
        return date.fromisoformat(text[:10]) if len(text) >= 10 else None
    except ValueError:
        return None


def _words(value: Any) -> tuple[str, ...]:
    """A reading's building field as words: one value, or a list of them; empty when the reading names none."""
    if value in (None, "", [], ()):
        return ()
    values = value if isinstance(value, (list, tuple)) else [value]
    return tuple(str(v).strip() for v in values if str(v).strip())


@dataclass(frozen=True)
class Report:
    """One inspection report as its reading gives it. ``kind`` and ``day`` are None, and ``buildings`` empty, where
    the reading does not say; ``model`` is empty where no reader read it."""

    id: str
    name: str
    model: str = ""
    day: date | None = None
    kind: SystemKind | None = None
    system_word: str = ""
    buildings: tuple[str, ...] = ()
    interval_months: int | None = None
    result: str = ""
    deficiencies: int = 0
    open_deficiencies: int = 0
    confidential: bool = False
    has_text: bool = True

    @classmethod
    def of(cls, row: Mapping[str, Any]) -> "Report":
        """A row of the readings store. Only the reading's own fields are read: not the file's name or its period."""
        fields = row.get("fields") or {}
        word = str(fields.get("system") or "").strip().lower()
        interval = fields.get("interval_months")
        return cls(
            id=str(row.get("id") or ""), name=str(row.get("name") or ""), model=str(row.get("model") or ""),
            day=_day(fields.get("inspection_date")), kind=SYSTEM_WORDS.get(word), system_word=word,
            buildings=_words(fields.get("buildings")) or _words(fields.get("building")),
            interval_months=int(interval) if str(interval or "").isdigit() and int(interval) else None,
            result=str(fields.get("result") or ""), deficiencies=len(fields.get("deficiencies") or ()),
            open_deficiencies=int(fields.get("open_deficiencies") or 0),
            confidential=bool(row.get("confidential")), has_text=bool(row.get("hasText", True)))

    @property
    def where(self) -> str:
        return "Drive" if self.id.startswith("drive-") else "library"

    @property
    def label(self) -> str:
        """The document's name, date, and id. A confidential file's name is held back."""
        name = "a confidential document" if self.confidential else (self.name or "an unnamed document")
        when = f"{self.day}, " if self.day else ""
        return f"{name} ({when}{self.where} id {self.id})"

    @property
    def reader(self) -> str:
        return f"the reader {self.model}" if self.model else "no reader"

    @property
    def reports_deficiencies(self) -> bool:
        return bool(self.deficiencies or self.open_deficiencies)

    def as_dict(self) -> dict[str, Any]:
        return {"id": self.id, "name": "" if self.confidential else self.name, "where": self.where,
                "date": self.day.isoformat() if self.day else None, "system": self.kind.value if self.kind else None,
                "buildings": list(self.buildings), "intervalMonths": self.interval_months, "result": self.result,
                "deficiencies": max(self.deficiencies, self.open_deficiencies), "openDeficiencies": self.open_deficiencies,
                "model": self.model, "confidential": self.confidential}


@dataclass(frozen=True)
class Completion:
    """A completion a person recorded for a scheduled assignment (``jason.tasks.schedule.record_done``), with the
    obligations that assignment covers."""

    key: str
    done: date | None
    by: str = ""
    evidence: str = ""
    due: date | None = None
    obligations: tuple[str, ...] = ()

    @property
    def label(self) -> str:
        return (f"recorded done on {self.done} by {self.by or 'a person'} (assignment {self.key})"
                + (f": {self.evidence}" if self.evidence else ""))

    def as_dict(self) -> dict[str, Any]:
        return {"assignment": self.key, "done": self.done.isoformat() if self.done else None, "by": self.by,
                "due": self.due.isoformat() if self.due else None, "evidence": self.evidence}


