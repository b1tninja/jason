@dataclass(frozen=True)
class Unplaced:
    """A record on file that no period holds, and the field or fact it lacks."""

    label: str
    reason: str
    id: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {"record": self.label, "reason": self.reason, "id": self.id}


@dataclass(frozen=True)
class Placed:
    """A report placed on a system: the buildings of the system it covers (one empty word for a system the
    specification does not divide by building), and, for one that reports deficiencies, the later report on file
    that reads passed with none open."""

    report: Report
    system: LifeSafetySystem
    slots: tuple[str, ...]
    correction: Report | None = None

    def deficiency_text(self) -> str:
        r = self.report
        if not r.reports_deficiencies:
            return ""
        n = max(r.deficiencies, r.open_deficiencies)
        text = f"{n} deficienc{'y' if n == 1 else 'ies'} reported" + (f", {r.open_deficiencies} open" if r.open_deficiencies else "")
        if self.correction is not None:
            return f"{text}; a later report on file reads passed with none open: {self.correction.label}"
        return f"{text}; no correction on file"

    def as_dict(self) -> dict[str, Any]:
        row = {**self.report.as_dict(), "placedOn": [s for s in self.slots if s]}
        if self.report.reports_deficiencies:
            row["correction"] = self.correction.as_dict() if self.correction else None
            row["correctionNote"] = ("a later report reads passed with none open; its result, not a record of the repair"
                                     if self.correction else "no correction on file")
        return row


