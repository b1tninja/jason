# The record-keeping rule, recited.


@dataclass(frozen=True)
class Recital:
    """A record-keeping provision's words from the shelf, or why they are not there. ``reaches`` are the listed
    systems the row's condition holds for; ``asks`` the questions where it cannot be decided."""

    rule: RecordRule
    found: bool = False
    words: str = ""
    source: str = ""
    reason: str = ""
    reaches: tuple[str, ...] = ()
    asks: tuple[str, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        return {"key": self.rule.key, "citation": self.rule.citation, "about": self.rule.about, "found": self.found,
                "words": self.words, "source": self.source, "reason": self.reason, "reaches": list(self.reaches),
                "condition": self.rule.applies.describe(), "questions": list(self.asks)}


_PAGE_MARK = re.compile(r"<<PAGE \d+>>\s*$")
# A section's first line: "§904.1. Inspection Requirements." or "904.2. Testing ...". A list item ("1. ...") is not one.
_HEADING = re.compile(r"(?:§\s*\d+|\d{2,})(?:\.\d+)*\.\s+\S")


def _shelf_lines(text: str) -> list[str]:
    """A publication's text without its page marks, and without the page number printed just before each."""
    lines = text.splitlines()
    drop: set[int] = set()
    for i, line in enumerate(lines):
        if not _PAGE_MARK.match(line.strip()):
            continue
        drop.add(i)
        j = i - 1
        while j >= 0 and not lines[j].strip():
            j -= 1
        if j >= 0 and re.fullmatch(r"\d{1,4}", lines[j].strip()):
            drop.add(j)
    return [line for i, line in enumerate(lines) if i not in drop]


def recite(data_dir: Path | str, rule: RecordRule, *, publications: Iterable[Any] | None = None) -> Recital:
    """The provision's words as the shelf's copy of its publication prints them, found by the row's locator: the
    section's first line, the provision's first line inside it, and the first line after it. A miss names why, and
    nothing is quoted."""
    from jason.tasks.export_authorities import PUBLICATIONS_DIR

    if publications is None:
        from jason.community.authorities import PUBLICATIONS as publications
    pub = next((p for p in publications if p.title == rule.publication), None)
    if pub is None:
        return Recital(rule, reason=f"no publication titled \"{rule.publication}\" is listed for the shelf")
    path = Path(data_dir) / PUBLICATIONS_DIR / pub.text_filename
    source = f"{pub.title} ({pub.agency}), {PUBLICATIONS_DIR}/{pub.text_filename}"
    if not path.is_file():
        return Recital(rule, source=source, reason=f"{PUBLICATIONS_DIR}/{pub.text_filename} is not on disk; run "
                                                   "jason export-authorities")
    lines = _shelf_lines(path.read_text(encoding="utf-8", errors="replace"))
    section, start, end = (re.compile(p) for p in (rule.section, rule.start, rule.end))
    seen = False
    for i, line in enumerate(lines):
        if not section.match(line.strip()):
            continue
        seen = True
        for j in range(i + 1, len(lines)):
            here = lines[j].strip()
            if _HEADING.match(here) or section.match(here):
                break                                   # the next section: the provision is not in this one
            if not start.match(here):
                continue
            body = [here]
            for nxt in lines[j + 1:]:
                nxt = nxt.strip()
                if end.match(nxt) or _HEADING.match(nxt):
                    break
                body.append(nxt)
            return Recital(rule, True, " ".join(" ".join(body).split()), source)
    reason = ("the shelf's copy prints the section without this provision" if seen
              else "the shelf's copy does not print the section")
    return Recital(rule, source=source, reason=reason)


