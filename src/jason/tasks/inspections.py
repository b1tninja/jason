def _why_groups(findings: Sequence[Finding]) -> list[tuple[str, list[Finding]]]:
    groups: dict[str, list[Finding]] = {}
    for f in findings:
        groups.setdefault(f.why(), []).append(f)
    return list(groups.items())


def _report_line(p: Placed) -> str:
    where = f"building {', '.join(s for s in p.slots if s)}: " if any(p.slots) else ""
    parts = [f"{where}{p.report.label}"]
    if p.report.result:
        parts.append(f"result {p.report.result}")
    if p.deficiency_text():
        parts.append(p.deficiency_text())
    return "; ".join(parts)


def _period_lines(period: Period) -> list[str]:
    out = [f"{period.label}: {period.status.value}"]
    out += [f"  {_report_line(p)}" for p in period.reports]
    out += [f"  {c.label}" for c in period.completions]
    if period.missing:
        out.append(f"  nothing on file for building {', '.join(period.missing)}")
    if period.note:
        out.append(f"  {period.note}")
    return out


def _counts_text(o: ObligationRecords) -> str:
    counts = o.counts()
    return ", ".join(f"{counts[c.value]} {c.value}" for c in Coverage)


def _calendar_text(o: ObligationRecords) -> str:
    cal = o.calendar or {}
    if not cal:
        return ""
    last = f", last {cal['lastDone']}" if cal.get("lastDone") else ""
    return f"jason deadlines: next {cal.get('next') or 'none'}, {cal.get('standing')}{last}"


def _recital_lines(recitals: Sequence[Recital]) -> list[str]:
    out = []
    for r in recitals:
        out.append(f"{r.rule.citation} ({r.rule.about})")
        if r.found:
            out.append(f"  \"{r.words}\"")
            out.append(f"  from {r.source}")
        else:
            out.append(f"  Its words are not on the authorities shelf ({r.reason}), so it is cited and not quoted.")
            if r.source:
                out.append(f"  looked in {r.source}")
        reach = ", ".join(r.reaches) or "no listed system"
        out.append(f"  a reading: by the row's condition ({r.rule.applies.describe()}) it reaches {reach}")
        out += [f"  question: {q}" for q in r.asks]
    return out


def lines(records: Records) -> list[str]:
    """The result as plain lines, a system at a time."""
    out: list[str] = []
    if not records.listed:
        out += ["The specification lists no life safety systems (Community.life_safety_systems()).", ""]
    for s in records.systems:
        system = s.system
        out.append(f"{system.name} ({system.kind.label})")
        if system.served():
            out.append(f"  serves: {system.served()}")
        for o in s.obligations:
            out.append(f"  {row_name(o.row)} ({cadence_of(o.row)})")
            if getattr(o.row, "authority", ""):
                out.append(f"    authority, as the row cites it: {o.row.authority}")
            if o.counted_from:
                out.append(f"    counted from {o.counted_from}, {o.counted_how}")
            else:
                out.append(f"    {o.counted_how}")
            if _calendar_text(o):
                out.append(f"    {_calendar_text(o)}")
            for period in o.periods:
                out += [f"    {line}" for line in _period_lines(period)]
            if o.earlier:
                out.append("    before the first period:")
                out += [f"      {_report_line(p)}" for p in o.earlier]
            if o.periods:
                out.append(f"    periods: {_counts_text(o)}")
        if not s.obligations:
            out.append("  no obligation with periods applies; nothing is expected of it here")
        if s.unassigned:
            out.append(f"  on file, not assigned to an obligation ({len(s.unassigned)})")
            for p, why in s.unassigned:
                out += [f"    {_report_line(p)}", f"      {why}"]
        if s.not_read:
            out.append(f"  filed, not read ({len(s.not_read)}): from a vendor the specification names for this system")
            out += [f"    {f.name} (sent {f.sent or 'undated'} by {f.vendor}; filed in {f.where or 'Drive'})" for f in s.not_read]
        if s.undetermined:
            out.append(f"  undetermined ({len(s.undetermined)})")
            for f in s.undetermined:
                out += [f"    {row_name(f.row)}", f"      question: {f.question()}"]
        if s.does_not_apply:
            out.append(f"  does not apply ({len(s.does_not_apply)}): nothing is expected")
            for why, findings in _why_groups(s.does_not_apply):
                out.append(f"    decided by {why}:")
                out += [f"      {row_name(f.row)}" for f in findings]
        out.append("")
    out.append(f"Unplaced ({len(records.unplaced)})")
    for u in records.unplaced:
        out += [f"  {u.label}", f"    {u.reason}"]
    if not records.unplaced:
        out.append("  none")
    if records.other_filings:
        out.append(f"  {records.other_filings} inspection report(s) in the filing log are from vendors no listed system "
                   "names, and are left out.")
    out += ["", "Record keeping"]
    out += [f"  {line}" for line in _recital_lines(records.recitals)] or ["  no record-keeping provision is listed"]
    if records.questions:
        out += ["", f"Questions for a person ({len(records.questions)})"]
        out += [f"  {q}" for q in records.questions]
    out.append("")
    out += [f"* {c}" for c in CAVEATS]
    return out


def markdown(records: Records) -> str:
    """The page ``--write`` saves: the same result in Markdown, under a header that says what it is."""
    name = records.community or "The association"
    out = [f"# Life safety records on file: {name}", "",
           f"Generated by jason on {date.today().isoformat()}, as of {records.as_of.isoformat()}, from the documents "
           "listed below. It is a summary, not the record: each line names the document it rests on, and the document "
           "governs.", ""]
    if records.sources:
        out += ["Read from: " + "; ".join(records.sources) + ".", ""]
    if not records.listed:
        out += ["The specification lists no life safety systems (`Community.life_safety_systems()`).", ""]
    if records.summary():
        out += ["## Summary", "", "| System | Obligation | Frequency | Covered | Partly on file | Not on file | Not yet due | Note |",
                "|---|---|---|---|---|---|---|---|"]
        names = {s.system.key: s.system.name for s in records.systems}
        for row in records.summary():
            out.append(f"| {names[row['system']]} | {row['obligation']} | {row['cadence']} | {row[Coverage.COVERED.value]} | "
                       f"{row[Coverage.PARTLY.value]} | {row[Coverage.NOT_ON_FILE.value]} | {row[Coverage.NOT_YET_DUE.value]} | "
                       f"{_cell(row['note'])} |")
        out.append("")
    for s in records.systems:
        system = s.system
        out += [f"## {system.name}", "", f"A {system.kind.label}" + (f", serving {system.served()}." if system.served() else "."), ""]
        for o in s.obligations:
            out += [f"### {row_name(o.row)}", "", f"- Frequency: {cadence_of(o.row)}"]
            if getattr(o.row, "authority", ""):
                out.append(f"- Authority, as the row cites it: {o.row.authority}")
            out.append(f"- Counted from {o.counted_from}, {o.counted_how}." if o.counted_from else f"- {o.counted_how}")
            if _calendar_text(o):
                out.append(f"- {_calendar_text(o)}")
            out.append("")
            if o.periods:
                out += ["| Period | Standing | On file |", "|---|---|---|"]
                for p in o.periods:
                    held = [_report_line(r) for r in p.reports] + [c.label for c in p.completions]
                    if p.missing:
                        held.append(f"nothing on file for building {', '.join(p.missing)}")
                    if p.note:
                        held.append(p.note)
                    out.append(f"| {p.label} | {p.status.value} | {'<br>'.join(_cell(h) for h in held) or 'nothing'} |")
                out.append("")
            if o.earlier:
                out += ["Before the first period:", ""] + [f"- {_report_line(p)}" for p in o.earlier] + [""]
        if not s.obligations:
            out += ["No obligation with periods applies; nothing is expected of it here.", ""]
        if s.unassigned:
            out += ["### On file, not assigned to an obligation", ""]
            out += [f"- {_report_line(p)}. {why}." for p, why in s.unassigned] + [""]
        if s.not_read:
            out += ["### Filed, not read", "", "From a vendor the specification names for this system; no reader has "
                    "read them, so none is placed in a period.", ""]
            out += [f"- {f.name} (sent {f.sent or 'undated'} by {f.vendor}; filed in {f.where or 'Drive'})" for f in s.not_read] + [""]
        if s.undetermined:
            out += ["### Undetermined", ""]
            out += [f"- {row_name(f.row)}: {f.question()}" for f in s.undetermined] + [""]
        if s.does_not_apply:
            out += ["### Does not apply", "", "Nothing is expected for these, and the fact that decided each is named.", ""]
            for why, findings in _why_groups(s.does_not_apply):
                out.append(f"- Decided by {why}: " + "; ".join(row_name(f.row) for f in findings))
            out.append("")
    out += ["## Unplaced", ""]
    out += [f"- {u.label}: {u.reason}" for u in records.unplaced] or ["None."]
    if records.other_filings:
        out.append(f"- {records.other_filings} inspection report(s) in the filing log are from vendors no listed system "
                   "names, and are left out.")
    out += ["", "## Record keeping", ""]
    for r in records.recitals:
        out.append(f"**{r.rule.citation}** ({r.rule.about})")
        out.append("")
        if r.found:
            out += [f"> \"{r.words}\"", "", f"From {r.source}."]
        else:
            out.append(f"Its words are not on the authorities shelf ({r.reason}), so it is cited and not quoted.")
        out.append(f"A reading: by the row's condition ({r.rule.applies.describe()}) it reaches "
                   f"{', '.join(r.reaches) or 'no listed system'}.")
        out += [f"Question: {q}" for q in r.asks]
        out.append("")
    if records.questions:
        out += ["## Questions for a person", ""] + [f"- {q}" for q in records.questions] + [""]
    out += ["## How to read this page", ""] + [f"- {c}" for c in CAVEATS] + [""]
    return "\n".join(out)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def write(data_dir: Path | str, records: Records) -> Path:
    """Save the page under the data root (``reports/life-safety-records.md``), holding its store lock."""
    from jason.locks import Resource, hold

    path = Path(data_dir) / PAGE
    with hold(Resource.STORE, LOCK_KEY, timeout=120, purpose="jason inspections --write"):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(markdown(records), encoding="utf-8")
    return path


