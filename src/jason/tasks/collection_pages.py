@dataclass(frozen=True)
class PagesSource:
    """One collection's generated pages for the passage index (``passage_index.build``): every Markdown page in its
    folder, in the collection's own catalog, with the standing ``page``, generated, and as confidential as the
    collection. A hit on one is a summary, never the record."""

    collection: Collection

    @property
    def catalog(self) -> str:
        return self.collection.page_catalog

    @property
    def catalogs(self) -> tuple[str, ...]:
        return (self.catalog,)

    @property
    def folder(self) -> str:
        return self.collection.pages_folder

    def entries(self, data_dir: Path) -> Iterable[IndexFile]:
        root = Path(data_dir) / self.folder
        if not root.is_dir():
            return
        context = f"{SUMMARY_LABEL} ({self.collection.title})"
        for path in sorted(root.glob("*.md")):
            yield IndexFile(path, self.catalog, Standing.PAGE, kind="", confidential=self.collection.confidential,
                            generated=True, context=context)


def index_sources(collections: Iterable[Collection]) -> tuple[PagesSource, ...]:
    """One ``PagesSource`` per collection: its generated pages, in its own catalog."""
    return tuple(PagesSource(found) for found in collections)


